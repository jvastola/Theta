//! Simple bitmap font atlas and text rendering.
//!
//! Generates a rasterized ASCII font atlas at startup and provides
//! helpers to build vertex buffers for rendering text as textured quads.

/// A generated bitmap font atlas.
pub struct FontAtlas {
    /// RGBA pixel data (width * height * 4 bytes).
    pub pixels: Vec<u8>,
    pub width: u32,
    pub height: u32,
    /// Width of a single character cell in pixels.
    pub cell_width: u32,
    /// Height of a single character cell in pixels.
    pub cell_height: u32,
    /// Number of columns in the atlas grid.
    pub cols: u32,
    /// Number of rows in the atlas grid.
    pub rows: u32,
}

impl FontAtlas {
    /// Generate a bitmap font atlas covering ASCII 32..127.
    /// Each character is rendered in a `cell_w x cell_h` box using a simple
    /// built-in bitmap font (5×7 glyphs, scaled up).
    pub fn generate(cell_w: u32, cell_h: u32) -> Self {
        let first_char = 32u8;
        let last_char = 127u8;
        let count = (last_char - first_char + 1) as u32;
        let cols = 16u32;
        let rows = (count + cols - 1) / cols;

        let width = cols * cell_w;
        let height = rows * cell_h;
        let mut pixels = vec![0u8; (width * height * 4) as usize];

        for ch in first_char..=last_char {
            let idx = (ch - first_char) as u32;
            let col = idx % cols;
            let row = idx / cols;
            let glyph = GLYPH_5X7.get(ch as usize).unwrap_or(&GLYPH_5X7[0]);

            // Scale factor: glyph is 5×7, cell is cell_w × cell_h
            let sx = cell_w / 5;
            let sy = cell_h / 7;

            for gy in 0..7u32 {
                for gx in 0..5u32 {
                    let bit = glyph[gy as usize] & (1 << (4 - gx));
                    if bit != 0 {
                        // Fill the scaled pixel block
                        for dy in 0..sy {
                            for dx in 0..sx {
                                let px = col * cell_w + gx * sx + dx;
                                let py = row * cell_h + gy * sy + dy;
                                let offset = ((py * width + px) * 4) as usize;
                                pixels[offset] = 255;     // R
                                pixels[offset + 1] = 255; // G
                                pixels[offset + 2] = 255; // B
                                pixels[offset + 3] = 255; // A
                            }
                        }
                    }
                }
            }
        }

        Self {
            pixels,
            width,
            height,
            cell_width: cell_w,
            cell_height: cell_h,
            cols,
            rows,
        }
    }
}

/// Vertex for a screen-space textured quad.
#[repr(C)]
#[derive(Copy, Clone, Debug, bytemuck::Pod, bytemuck::Zeroable)]
pub struct TextVertex {
    /// Screen-space position in pixels.
    pub position: [f32; 2],
    /// UV coordinate into the font atlas.
    pub uv: [f32; 2],
    /// RGBA color (so we can tint text).
    pub color: [f32; 4],
}

impl TextVertex {
    pub fn desc() -> wgpu::VertexBufferLayout<'static> {
        wgpu::VertexBufferLayout {
            array_stride: std::mem::size_of::<TextVertex>() as wgpu::BufferAddress,
            step_mode: wgpu::VertexStepMode::Vertex,
            attributes: &[
                wgpu::VertexAttribute {
                    offset: 0,
                    shader_location: 0,
                    format: wgpu::VertexFormat::Float32x2,
                },
                wgpu::VertexAttribute {
                    offset: std::mem::size_of::<[f32; 2]>() as wgpu::BufferAddress,
                    shader_location: 1,
                    format: wgpu::VertexFormat::Float32x2,
                },
                wgpu::VertexAttribute {
                    offset: std::mem::size_of::<[f32; 4]>() as wgpu::BufferAddress,
                    shader_location: 2,
                    format: wgpu::VertexFormat::Float32x4,
                },
            ],
        }
    }
}

/// Build a list of textured quads for rendering a string.
/// `x, y` is the top-left corner in screen pixels.
/// `scale` multiplies the cell size.
/// `color` is the text color [R, G, B, A] in 0..1.
pub fn build_text_vertices(
    text: &str,
    x: f32,
    y: f32,
    scale: f32,
    color: [f32; 4],
    atlas: &FontAtlas,
) -> (Vec<TextVertex>, Vec<u16>) {
    let mut vertices = Vec::new();
    let mut indices = Vec::new();
    let cw = atlas.cell_width as f32 * scale;
    let ch = atlas.cell_height as f32 * scale;
    let inv_w = 1.0 / atlas.width as f32;
    let inv_h = 1.0 / atlas.height as f32;

    for (i, ch_byte) in text.bytes().enumerate() {
        let ch_byte = if ch_byte >= 32 && ch_byte < 127 { ch_byte } else { b'?' };
        let idx = (ch_byte - 32) as u32;
        let col = idx % atlas.cols;
        let row = idx / atlas.rows;

        let u0 = (col * atlas.cell_width) as f32 * inv_w;
        let v0 = (row * atlas.cell_height) as f32 * inv_h;
        let u1 = ((col + 1) * atlas.cell_width) as f32 * inv_w;
        let v1 = ((row + 1) * atlas.cell_height) as f32 * inv_h;

        let x0 = x + i as f32 * cw;
        let y0 = y;
        let x1 = x0 + cw;
        let y1 = y0 + ch;

        let base = vertices.len() as u16;
        vertices.push(TextVertex { position: [x0, y0], uv: [u0, v0], color });
        vertices.push(TextVertex { position: [x1, y0], uv: [u1, v0], color });
        vertices.push(TextVertex { position: [x1, y1], uv: [u1, v1], color });
        vertices.push(TextVertex { position: [x0, y1], uv: [u0, v1], color });

        indices.extend_from_slice(&[
            base, base + 1, base + 2,
            base + 2, base + 3, base,
        ]);
    }

    (vertices, indices)
}

